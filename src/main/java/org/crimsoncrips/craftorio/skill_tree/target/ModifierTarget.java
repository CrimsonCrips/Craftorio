package org.crimsoncrips.craftorio.skill_tree.target;

public enum ModifierTarget {
    MULTIPLIER,
    ITEM_BASE_VALUE,
    ITEM_TAG_BASE_VALUE,
    CONTRACT_REFRESH_SPEED,
    EFFECT_TIMER_SPEED,
    PUNISHMENT_DURATION,
    EFFECT_DURATION,
    EXPANSION_COST,
    RARER_CONTRACT_CHANCE,
    RARER_EFFECT_CHANCE,
    SHOP_COST,
    CONTRACT_REFRESH_COST,
    LOST_BET_REFUND,
    MULT_PER_CONTRACT_DONE,
    BET_ODDS,
    BET_BONUS,
    MANUAL_SINK_VALUE,
    VALUE_CONDENSER_CAP,
    BUILD_BLITZ_COOLDOWN,
    BUILD_BLITZ_COVERAGE;

    public boolean isDuration() {
        return this == CONTRACT_REFRESH_SPEED || this == EFFECT_TIMER_SPEED || this == PUNISHMENT_DURATION
                || this == EFFECT_DURATION || this == BUILD_BLITZ_COOLDOWN;
    }
}
